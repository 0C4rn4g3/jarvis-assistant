"""Headless Minecraft/Spigot/Paper Test Server Controller.
Spins up a local test Paper/Spigot server in the background with hidden console,
hot-deploys compiled plugin JARs, and tails logs/latest.log to audit
plugin initialization, exceptions, and lifecycle events cleanly.
"""
import glob
import os
import re
import shutil
import subprocess
import time
from typing import Any, Dict, List, Optional

NO_WINDOW = subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0
DEFAULT_SERVER_DIR = os.path.join(os.path.expanduser("~"), ".jarvis", "spigot_server")
os.makedirs(DEFAULT_SERVER_DIR, exist_ok=True)

# Active server process holder: { "proc": Popen, "dir": str, "started_at": float }
_active_server: Dict[str, Any] = {"proc": None, "dir": None, "started_at": 0.0}


def find_server_jar(server_dir: str) -> Optional[str]:
    """Finds paper.jar, spigot.jar, or server.jar in the server directory."""
    patterns = ["paper*.jar", "spigot*.jar", "server*.jar", "*.jar"]
    for pat in patterns:
        matches = glob.glob(os.path.join(server_dir, pat))
        jars = [m for m in matches if not os.path.basename(m).startswith("original-")]
        if jars:
            jars.sort(key=os.path.getsize, reverse=True)
            return jars[0]
    return None


def ensure_eula(server_dir: str):
    """Ensures eula.txt has eula=true."""
    eula_file = os.path.join(server_dir, "eula.txt")
    if not os.path.exists(eula_file) or "eula=false" in open(eula_file, encoding="utf-8", errors="replace").read():
        with open(eula_file, "w", encoding="utf-8") as f:
            f.write("# Auto-generated by Jarvis\neula=true\n")


def is_server_running() -> bool:
    """Checks if background test server process is alive."""
    proc = _active_server.get("proc")
    if proc is not None:
        if proc.poll() is None:
            return True
        _active_server["proc"] = None
    return False


def start_server(server_dir: str = "", xmx: str = "2G") -> Dict[str, Any]:
    """Starts local Minecraft server in background with CREATE_NO_WINDOW."""
    server_dir = os.path.abspath(server_dir or DEFAULT_SERVER_DIR)
    os.makedirs(server_dir, exist_ok=True)
    os.makedirs(os.path.join(server_dir, "plugins"), exist_ok=True)

    if is_server_running():
        return {
            "status": "already_running",
            "pid": _active_server["proc"].pid,
            "dir": _active_server["dir"],
            "uptime_sec": round(time.time() - _active_server["started_at"], 1),
        }

    jar_path = find_server_jar(server_dir)
    if not jar_path:
        return {
            "status": "error",
            "error": f"No server JAR (paper.jar, spigot.jar) found in {server_dir}. Place a Paper/Spigot jar there.",
            "dir": server_dir,
        }

    ensure_eula(server_dir)

    cmd = [
        "java",
        "-Xms512M",
        f"-Xmx{xmx}",
        "-XX:+UseG1GC",
        "-jar",
        os.path.basename(jar_path),
        "--nogui",
    ]

    try:
        proc = subprocess.Popen(
            cmd,
            cwd=server_dir,
            stdin=subprocess.PIPE,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=NO_WINDOW
        )
        _active_server["proc"] = proc
        _active_server["dir"] = server_dir
        _active_server["started_at"] = time.time()

        return {
            "status": "started",
            "pid": proc.pid,
            "jar": os.path.basename(jar_path),
            "dir": server_dir,
        }
    except Exception as e:
        return {"status": "error", "error": str(e)}


def stop_server() -> Dict[str, Any]:
    """Gracefully stops or terminates test server."""
    if not is_server_running():
        return {"status": "not_running"}

    proc = _active_server["proc"]
    try:
        if proc.stdin:
            proc.stdin.write(b"stop\n")
            proc.stdin.flush()
        proc.wait(timeout=10)
    except Exception:
        proc.kill()

    _active_server["proc"] = None
    return {"status": "stopped"}


def deploy_plugin(plugin_jar: str, server_dir: str = "") -> Dict[str, Any]:
    """Copies compiled plugin JAR into plugins folder and triggers reload."""
    if not os.path.exists(plugin_jar):
        return {"status": "error", "error": f"Plugin JAR not found: {plugin_jar}"}

    server_dir = os.path.abspath(server_dir or _active_server.get("dir") or DEFAULT_SERVER_DIR)
    plugins_dir = os.path.join(server_dir, "plugins")
    os.makedirs(plugins_dir, exist_ok=True)

    dest = os.path.join(plugins_dir, os.path.basename(plugin_jar))
    shutil.copy2(plugin_jar, dest)

    reloaded = False
    if is_server_running():
        proc = _active_server["proc"]
        try:
            if proc.stdin:
                proc.stdin.write(b"reload confirm\n")
                proc.stdin.flush()
                reloaded = True
        except Exception:
            pass

    return {
        "status": "deployed",
        "jar": os.path.basename(plugin_jar),
        "destination": dest,
        "server_running": is_server_running(),
        "reload_sent": reloaded,
    }


def audit_server_logs(server_dir: str = "", max_lines: int = 100) -> Dict[str, Any]:
    """Tails logs/latest.log and detects exceptions or successful plugin loading."""
    server_dir = os.path.abspath(server_dir or _active_server.get("dir") or DEFAULT_SERVER_DIR)
    log_file = os.path.join(server_dir, "logs", "latest.log")

    if not os.path.exists(log_file):
        return {"status": "no_log", "log_file": log_file, "exceptions": []}

    try:
        with open(log_file, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
    except Exception as e:
        return {"status": "error", "error": str(e)}

    tail = lines[-max_lines:]
    tail_text = "".join(tail)

    # Detect exceptions
    exception_patterns = [
        re.compile(r"Could not load '.*?' in folder '.*?'", re.I),
        re.compile(r"org\.bukkit\.plugin\.InvalidPluginException:.*"),
        re.compile(r"java\.lang\.ClassNotFoundException:.*"),
        re.compile(r"java\.lang\.NullPointerException:.*"),
        re.compile(r"\[ERROR\]\s+.*"),
        re.compile(r"Error occurred while enabling .*"),
    ]

    found_exceptions = []
    for line in tail:
        for pat in exception_patterns:
            if pat.search(line):
                found_exceptions.append(line.strip())

    # Detect loaded plugins
    loaded_plugins = re.findall(r"\[INFO\]\s+\[(.*?)\]\s+Enabling\s+\1", tail_text)
    server_ready = "Done (" in tail_text or "For help, type \"help\"" in tail_text

    return {
        "status": "exception_detected" if found_exceptions else "healthy",
        "server_ready": server_ready,
        "loaded_plugins": list(set(loaded_plugins)),
        "exceptions": found_exceptions[:8],
        "log_tail": "".join(tail[-20:]),
    }
